export function detectChecklistTemplate(methodName = ""): ChecklistTemplateType {
  const lower = methodName.toLowerCase();
  if (lower.includes("аукцион")) return "auction";
  if (lower.includes("конкурс")) return "open_tender";
  if (lower.includes("ценов") || lower.includes("зцп")) return "price_quote";
  if (lower.includes("источник")) return "single_source";
  return "standard";
}
